#!/usr/bin/env python3
"""Export Olist warehouse tables for Power BI Import mode.

Writes CSVs under powerbi/data/ that match the star schema + analytics
tables Power BI needs for the five UrbanCart dashboards.
"""

from __future__ import annotations

import os
from pathlib import Path

import pandas as pd
from sqlalchemy import create_engine, text

ROOT = Path(__file__).resolve().parent
OUT = ROOT / "data"

DB_URL = os.getenv(
    "URBANCART_DB_URL",
    f"postgresql+psycopg2://{os.getenv('USER', 'postgres')}@localhost:5432/urbancart",
)

# Order matters only for logging; each is independent.
TABLES = [
    "dim_customers",
    "dim_products",
    "dim_date",
    "orders_fact",
    "analysis_params",
    "customer_metrics",
    "clv_table",
    "rfm_segmentation",
    "cohort_retention",
    "product_pairs",
    "category_pairs",
]

# Extra flat views that make Power BI visuals easier (no relationship required).
EXTRA_QUERIES = {
    "pbi_monthly_kpis": "SELECT * FROM monthly_kpis ORDER BY month",
    "pbi_state_revenue": "SELECT * FROM state_revenue ORDER BY revenue DESC",
    "pbi_category_performance": "SELECT * FROM category_performance ORDER BY revenue DESC",
    "pbi_churn_risk": "SELECT * FROM churn_risk",
    "pbi_clv_segmentation": "SELECT * FROM clv_segmentation",
    "pbi_customer_360": "SELECT * FROM customer_360_view",
}


def main() -> int:
    OUT.mkdir(parents=True, exist_ok=True)
    eng = create_engine(DB_URL)
    try:
        with eng.connect() as conn:
            conn.execute(text("SELECT 1 FROM orders_fact LIMIT 1"))
    except Exception as exc:
        print(
            "Cannot read urbancart warehouse. Run from project root:\n"
            "  python setup_local.py\n"
            f"Error: {exc}"
        )
        return 1

    print(f"Exporting Power BI dataset → {OUT}")
    with eng.connect() as conn:
        for name in TABLES:
            df = pd.read_sql(text(f"SELECT * FROM {name}"), conn)
            path = OUT / f"{name}.csv"
            df.to_csv(path, index=False)
            print(f"  {name:28} {len(df):>8,} rows")

        for name, sql in EXTRA_QUERIES.items():
            df = pd.read_sql(text(sql), conn)
            path = OUT / f"{name}.csv"
            df.to_csv(path, index=False)
            print(f"  {name:28} {len(df):>8,} rows")

    # Blank stub so the Measures table can host DAX only
    pd.DataFrame({"Dummy": ["x"]}).to_csv(OUT / "Measures.csv", index=False)

    # Manifest for Power BI / docs
    (OUT / "README.txt").write_text(
        "UrbanCart Power BI extract — Olist Brazilian E-Commerce\n"
        "Generated by powerbi/export_dataset.py after setup_local.py\n"
        "Connect Power BI Desktop → Get data → Folder → this data/ directory\n"
        "or use PostgreSQL (localhost / urbancart) for a live model.\n"
    )
    print("Done.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
